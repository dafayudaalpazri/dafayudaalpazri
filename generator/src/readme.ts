/**
 * README.md template. Only what GitHub's Markdown sanitiser keeps: <picture>/<source> for the theme, align,
 * width/height, <details>/<summary>, <sub>, <b>, <a>, <br>. No style attributes, no scripts, no external CSS.
 * Text that matters stays real text (headings live in the artwork's alt text; facts live in Markdown), so the
 * page still reads with images off.
 */
import type { Repo } from './data.ts';
import type { Stats } from './stats.ts';
import { fmtDate, fmtMonth } from './stats.ts';
import type { ProfileConfig } from '../profile.config.ts';
import type { SectionSpec } from './scenes/section.ts';
import { lanes } from './scenes/stack.ts';

export interface Built {
  hero: string;
  sections: Record<string, { path: string; spec: SectionSpec }>;
  stack: string;
  projects: { path: string; repo: Repo; blurb: string | null }[];
  telemetry: string;
  closing: string;
  links: { path: string; href: string; alt: string; width: number }[];
}

const attr = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function picture(path: string, alt: string, size = 'width="100%"'): string {
  return [
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./assets/${path}-dark.svg">`,
    `  <source media="(prefers-color-scheme: light)" srcset="./assets/${path}-light.svg">`,
    `  <img alt="${attr(alt)}" src="./assets/${path}-light.svg" ${size}>`,
    '</picture>',
  ].join('\n');
}

const center = (inner: string) => `<p align="center">\n${inner}\n</p>`;

export function readme(b: Built, s: Stats, config: ProfileConfig): string {
  const fill = (text: string) =>
    text.replace(/\{name\}/g, s.name).replace(/\{login\}/g, s.login).replace(/\{since\}/g, String(s.since)).replace(/\{bio\}/g, s.tagline);
  const sec = (key: string) => {
    const { path, spec } = b.sections[key];
    return center(picture(path, `${spec.index} · ${spec.title}: ${spec.note}`));
  };
  const out: string[] = [];

  out.push('<!-- Generated by generator/src/readme.ts from generator/profile.config.ts and public GitHub data. Edit those, then run `npm run build` in /generator. -->');
  out.push('');
  out.push(
    center(
      picture(
        b.hero,
        `${s.name} (@${s.login}): ${s.tagline}. Title card: an autofocus HUD hunts through floating cards${config.quote ? ` (a sticky note: "${config.quote}"` : ' ('}${config.song ? `${config.quote ? ', ' : ''}now playing ${config.song.title} by ${config.song.artist}` : ''}), then locks onto the name inside a black hole's shadow.`,
      ),
    ),
  );
  out.push('');
  out.push(`<p align="center"><b>${s.name}</b> · ${s.tagline}</p>`);
  out.push(center(b.links.map((l) => `<a href="${attr(l.href)}">${picture(l.path, l.alt, 'height="40"')}</a>`).join('\n')));
  out.push('');

  // 01 Singularity
  out.push(sec('singularity'));
  out.push('');
  for (const p of config.about) out.push(fill(p), '');
  if (config.now) out.push(`**Now:** ${config.now}`, '');

  // 02 Accretion
  out.push(sec('accretion'));
  out.push('');
  const L = lanes(s, config.stack);
  out.push(center(picture(b.stack, `Accretion: ${L.map((l) => `${l.label}: ${l.items.map((x) => x.name).join(', ')}`).join('. ')}.`)));
  out.push('');
  out.push('<details>');
  out.push('<summary><sub>Where these come from</sub></summary>');
  out.push('');
  out.push(
    `- **Languages** (${L[0].items.map((x) => x.name).join(', ')}): GitHub's language statistics for my ${s.originals.length} original public repos (forks left out).`,
  );
  for (const item of config.stack) out.push(`- **${item.name}**: ${item.source}.`);
  out.push('');
  out.push('</details>');
  out.push('');

  // 03 Orbits
  out.push(sec('orbits'));
  out.push('');
  for (const p of b.projects) {
    const alt = `${p.repo.name}${p.blurb ? `: ${p.blurb}` : ''}${p.repo.language ? ` ${p.repo.language}.` : ''} Updated ${fmtMonth(p.repo.pushedAt)}.`;
    out.push(center(`<a href="${attr(p.repo.url)}">\n${picture(p.path, alt)}\n</a>`));
  }
  const live = b.projects.filter((p) => p.repo.homepage);
  if (live.length)
    out.push(
      '',
      `<p align="center"><sub>Live: ${live.map((p) => `<a href="${attr(p.repo.homepage!)}">${p.repo.homepage!.replace(/^https?:\/\//, '').replace(/\/$/, '')}</a>`).join(' · ')}</sub></p>`,
    );
  out.push('');

  // 04 Telemetry
  out.push(sec('telemetry'));
  out.push('');
  out.push(
    center(
      picture(
        b.telemetry,
        `Telemetry, ${fmtDate(s.windowStart)} to ${fmtDate(s.windowEnd)}: ${s.total} contributions on ${s.activeDays} active days. Longest streak ${s.longestStreak} days. Biggest day ${s.biggestDay ? `${s.biggestDay.count} on ${fmtDate(s.biggestDay.date)}` : 'none'}. ${s.publicRepos} public repos, on GitHub since ${s.since}.`,
      ),
    ),
  );
  out.push('');
  out.push('<details>');
  out.push('<summary><sub>Reading the telemetry</sub></summary>');
  out.push('');
  out.push(`- **The ring** is the last 365 days (${fmtDate(s.windowStart)} to ${fmtDate(s.windowEnd)}), one tick per day, clockwise from the top. Gold spikes are days with public contributions; the longer the spike, the busier the day.`);
  out.push(`- **Counters** are counted from the same calendar: active days, the longest run of consecutive active days, the busiest day, month and weekday, public repos, and the year the account was created.`);
  out.push(`- **Languages** are the share of code by size in each original public repo, averaged so that every repo counts the same.`);
  out.push(`- **Kept current.** A GitHub Action checks the public data every day and redraws the images whenever something here changes; nothing is typed in by hand. Data as of ${s.updated}.`);
  out.push('');
  out.push('</details>');
  out.push('');

  out.push(center(picture(b.closing, `Thanks for falling in. See you beyond the horizon. The Singularity waves goodbye while a paper plane flies off.`)));
  out.push('');
  out.push(
    `<p align="center"><sub>Original artwork, drawn as SVG by the generator in <a href="./generator">/generator</a> from public GitHub data (last update ${s.updated}). Motion stops if your system asks for reduced motion.</sub></p>`,
  );
  out.push('');
  return out.join('\n');
}
